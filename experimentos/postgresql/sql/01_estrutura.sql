-- Marketplace Solidario | 4o periodo | Prova de conceito relacional
-- Executar no banco marketplace_solidario, em uma base nova.
-- 11 entidades da secao 18.1, com nomes do documento.
CREATE SCHEMA IF NOT EXISTS ms;

CREATE TABLE ms.usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    senha_hash TEXT, -- Sem credenciais reais nesta prova de conceito.
    tipo_usuario VARCHAR(20) NOT NULL
        CHECK (tipo_usuario IN ('DOADOR', 'INSTITUCIONAL', 'ADMINISTRADOR')),
    status VARCHAR(15) NOT NULL DEFAULT 'ATIVO'
        CHECK (status IN ('ATIVO', 'SUSPENSO')),
    data_cadastro TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ultimo_acesso TIMESTAMPTZ
);

CREATE TABLE ms.instituicao (
    id_instituicao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(180) NOT NULL,
    nome_fantasia VARCHAR(180),
    cnpj VARCHAR(18),
    descricao TEXT,
    telefone VARCHAR(30),
    email_contato VARCHAR(254),
    status VARCHAR(15) NOT NULL DEFAULT 'PENDENTE'
        CHECK (status IN ('PENDENTE', 'APROVADA', 'REJEITADA', 'SUSPENSA')),
    data_cadastro TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX uq_instituicao_cnpj ON ms.instituicao(cnpj) WHERE cnpj IS NOT NULL;

CREATE TABLE ms.membro_instituicao (
    id_membro BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES ms.usuario(id_usuario),
    id_instituicao BIGINT NOT NULL REFERENCES ms.instituicao(id_instituicao),
    papel VARCHAR(30) NOT NULL DEFAULT 'COLABORADOR'
        CHECK (papel IN ('ADMIN_INSTITUCIONAL', 'COLABORADOR')),
    status VARCHAR(15) NOT NULL DEFAULT 'ATIVO'
        CHECK (status IN ('ATIVO', 'INATIVO')),
    data_vinculo TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (id_usuario, id_instituicao)
);

CREATE TABLE ms.verificacao_instituicao (
    id_verificacao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_instituicao BIGINT NOT NULL REFERENCES ms.instituicao(id_instituicao),
    status_verificacao VARCHAR(15) NOT NULL DEFAULT 'PENDENTE'
        CHECK (status_verificacao IN ('PENDENTE', 'APROVADA', 'REJEITADA', 'EM_REVISAO')),
    data_solicitacao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    data_analise TIMESTAMPTZ,
    observacao TEXT,
    responsavel_analise BIGINT REFERENCES ms.usuario(id_usuario)
);

CREATE TABLE ms.categoria (
    id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    descricao TEXT,
    status VARCHAR(15) NOT NULL DEFAULT 'ATIVA'
        CHECK (status IN ('ATIVA', 'INATIVA')),
    requer_validacao_especial BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE ms.necessidade (
    id_necessidade BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_instituicao BIGINT NOT NULL REFERENCES ms.instituicao(id_instituicao),
    id_categoria BIGINT NOT NULL REFERENCES ms.categoria(id_categoria),
    titulo VARCHAR(180) NOT NULL,
    descricao TEXT,
    quantidade_solicitada INTEGER NOT NULL CHECK (quantidade_solicitada > 0),
    quantidade_confirmada INTEGER NOT NULL DEFAULT 0
        CHECK (quantidade_confirmada >= 0 AND quantidade_confirmada <= quantidade_solicitada),
    unidade_medida VARCHAR(40) NOT NULL,
    nivel_urgencia VARCHAR(15) NOT NULL DEFAULT 'MEDIA'
        CHECK (nivel_urgencia IN ('BAIXA', 'MEDIA', 'ALTA', 'CRITICA')),
    status VARCHAR(25) NOT NULL DEFAULT 'ABERTA'
        CHECK (status IN ('ABERTA', 'PARCIALMENTE_ATENDIDA', 'ATENDIDA', 'ENCERRADA')),
    data_publicacao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    data_limite TIMESTAMPTZ
);
CREATE INDEX ix_necessidade_instituicao ON ms.necessidade(id_instituicao);
CREATE INDEX ix_necessidade_categoria ON ms.necessidade(id_categoria);

CREATE TABLE ms.doacao (
    id_doacao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario_doador BIGINT NOT NULL REFERENCES ms.usuario(id_usuario),
    id_necessidade BIGINT NOT NULL REFERENCES ms.necessidade(id_necessidade),
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    status_doacao VARCHAR(15) NOT NULL DEFAULT 'RESERVADA'
        CHECK (status_doacao IN ('RESERVADA', 'ENTREGUE', 'CONFIRMADA', 'CANCELADA', 'EXPIRADA', 'RECUSADA')),
    data_criacao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    data_atualizacao TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX ix_doacao_necessidade ON ms.doacao(id_necessidade);

CREATE TABLE ms.reserva (
    id_reserva BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_doacao BIGINT NOT NULL UNIQUE REFERENCES ms.doacao(id_doacao),
    quantidade_reservada INTEGER NOT NULL CHECK (quantidade_reservada > 0),
    data_reserva TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    data_expiracao TIMESTAMPTZ NOT NULL,
    status_reserva VARCHAR(15) NOT NULL DEFAULT 'RESERVADA'
        CHECK (status_reserva IN ('RESERVADA', 'ENTREGUE', 'CONFIRMADA', 'CANCELADA', 'EXPIRADA'))
);
CREATE INDEX ix_reserva_status_expiracao ON ms.reserva(status_reserva, data_expiracao);

CREATE TABLE ms.entrega (
    id_entrega BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_doacao BIGINT NOT NULL UNIQUE REFERENCES ms.doacao(id_doacao),
    data_entrega TIMESTAMPTZ,
    status_entrega VARCHAR(15) NOT NULL DEFAULT 'INFORMADA'
        CHECK (status_entrega IN ('INFORMADA', 'CONFIRMADA', 'RECUSADA')),
    data_marcacao_doador TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    data_confirmacao_instituicao TIMESTAMPTZ,
    observacao TEXT
);

CREATE TABLE ms.localizacao (
    id_localizacao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_instituicao BIGINT NOT NULL REFERENCES ms.instituicao(id_instituicao),
    logradouro VARCHAR(180), numero VARCHAR(20), bairro VARCHAR(100),
    cidade VARCHAR(100) NOT NULL, estado CHAR(2) NOT NULL, cep VARCHAR(9),
    latitude NUMERIC(10,7), longitude NUMERIC(10,7),
    nivel_visibilidade VARCHAR(15) NOT NULL DEFAULT 'APROXIMADA'
        CHECK (nivel_visibilidade IN ('PUBLICA', 'APROXIMADA', 'RESTRITA')),
    CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180)
);

CREATE TABLE ms.notificacao (
    id_notificacao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES ms.usuario(id_usuario),
    tipo VARCHAR(50) NOT NULL,
    titulo VARCHAR(180) NOT NULL,
    mensagem TEXT NOT NULL,
    data_criacao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    data_leitura TIMESTAMPTZ,
    status VARCHAR(15) NOT NULL DEFAULT 'NAO_LIDA'
        CHECK (status IN ('NAO_LIDA', 'LIDA'))
);

-- A quantidade reservada e derivada das reservas ativas, evitando dupla fonte de verdade.
-- ENTREGUE permanece comprometida ate a confirmacao institucional (RN-016/017).
CREATE OR REPLACE VIEW ms.v_disponibilidade AS
SELECT n.id_necessidade, n.titulo, n.status,
       n.quantidade_solicitada,
       COALESCE(r.quantidade_reservada, 0)::INTEGER AS quantidade_reservada,
       n.quantidade_confirmada,
       (n.quantidade_solicitada - n.quantidade_confirmada
        - COALESCE(r.quantidade_reservada, 0))::INTEGER AS quantidade_disponivel
FROM ms.necessidade n
LEFT JOIN LATERAL (
    SELECT SUM(x.quantidade_reservada) AS quantidade_reservada
    FROM ms.reserva x JOIN ms.doacao d ON d.id_doacao = x.id_doacao
    WHERE d.id_necessidade = n.id_necessidade
      AND x.status_reserva IN ('RESERVADA', 'ENTREGUE')
) r ON TRUE;
